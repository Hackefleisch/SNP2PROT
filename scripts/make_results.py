#!/usr/bin/env python
"""Write `docs/RESULTS.md` — what the finished dataset contains, measured from it.

    python scripts/make_results.py

Every number here is read from the tables rather than typed, so the document cannot drift from
the data the way a hand-written summary does. Run it last, after `build_merged.py`.

It answers three questions in order: what is in the dataset, what it supports, and what it
does not. The third is not an appendix — a corpus whose label noise floor is 46% will happily
produce a model that looks excellent and has learned a laboratory.
"""

from __future__ import annotations

import pandas as pd
import pyarrow.dataset as ds

from snp2prot import clusters, label_health, thresholds
from snp2prot.config import (
    DOCS_DIR,
    PROCESSED_DIR,
    PROTEIN_TABLE,
    source_tables,
)

MERGED = PROCESSED_DIR / "training.parquet"


def _fmt(n) -> str:
    return f"{int(n):,}"


def corpus_domains() -> pd.DataFrame:
    """One row per distinct domain, with family, species and cluster."""
    frames = []
    for path in source_tables().values():
        cols = ["dbd_seq", "dbd_family", "species", "wt_id", "n_mut_from_wt", "source_dataset"]
        frames.append(
            ds.dataset(path).to_table(columns=cols).to_pandas().drop_duplicates("dbd_seq")
        )
    return pd.concat(frames, ignore_index=True).drop_duplicates("dbd_seq")


def main() -> None:
    cfg = thresholds.for_assay("pbm")
    records = label_health.load()
    inv = clusters.load()
    dom = corpus_domains()
    proteins = pd.read_parquet(PROTEIN_TABLE)
    merged_rows = ds.dataset(MERGED).count_rows() if MERGED.exists() else None

    kept = merge_survivors(records)
    n_pos, n_neg, n_gray = (int(kept[c].sum()) for c in ("n_pos", "n_neg", "n_gray"))
    calls = n_pos + n_neg
    variants = inv[inv.n_variants > 0]
    by_family = (
        dom[dom.n_mut_from_wt > 0]
        .groupby("dbd_family")
        .agg(variants=("dbd_seq", "nunique"))
        .join(variants.groupby("dbd_family").size().rename("clusters"), how="outer")
        .fillna(0)
        .astype(int)
        .sort_values("variants", ascending=False)
    )

    lines = [
        "# SNP2PROT — what is in the dataset",
        "",
        "Regenerated by `scripts/make_results.py`. Do not hand-edit: every figure is read from",
        "the tables, so this file and the data cannot disagree.",
        "",
        "## What it is",
        "",
        "A binary training set for *does this transcription-factor domain bind this DNA site?*,",
        "built to vary on **both axes at once** — the protein axis carries single-residue",
        "variants of the same domain, the DNA axis carries every 8-mer. One row is one",
        "(domain, 8-mer) pair with a label, the score behind it, and the provenance of both.",
        "",
        "Every row comes from a **universal protein-binding microarray**, and every protein was",
        "scored against the *same* 32,896 non-redundant 8-mers. That uniformity is the point:",
        "there is no assay-identity signal for a model to exploit, because there is only one",
        "assay and one 8-mer set.",
        "",
        "## Scale",
        "",
        "| | |",
        "|---|---:|",
    ]
    if merged_rows:
        lines.append(f"| rows in the merged table | {_fmt(merged_rows)} |")
    lines += [
        f"| distinct DNA-binding domains | {_fmt(len(kept))} |",
        f"| clusters | {_fmt(len(inv))} |",
        f"| clusters holding a variant | {_fmt(len(variants))} |",
        f"| variant domains | {_fmt(inv.n_variants.sum())} |",
        f"| Pfam families | {_fmt(dom.dbd_family.nunique())} |",
        f"| source organisms | {_fmt(dom.species.replace('', pd.NA).dropna().nunique())} |",
        f"| distinct 8-mers | {_fmt(32896)} (identical in every source) |",
        f"| sources | {len(source_tables())} |",
        "",
        "## Labels",
        "",
        f"`E >= {cfg['positive']}` is binding, `E <= {cfg['negative']}` is non-binding, and the",
        "band between them is a no-call kept in the table and excluded from training. Cutoffs",
        "are applied **per experiment** and written into every row, so a table describes its own",
        "binarization.",
        "",
        "| label | rows | share |",
        "|---|---:|---:|",
        f"| binding | {_fmt(n_pos)} | {n_pos / (n_pos + n_neg + n_gray):.3%} |",
        f"| non-binding | {_fmt(n_neg)} | {n_neg / (n_pos + n_neg + n_gray):.3%} |",
        f"| no call | {_fmt(n_gray)} | {n_gray / (n_pos + n_neg + n_gray):.3%} |",
        "",
        f"**{int(n_neg / n_pos)}:1 negative to positive** on calls made ({_fmt(n_pos)} of",
        f"{_fmt(calls)}). This is the assay and is retained deliberately: a universal PBM scores",
        "every protein against every 8-mer and a transcription factor binds a small minority of",
        "them. Every negative is *assayed and unbound*, recorded in `neg_provenance` on every",
        "negative row — not a site that merely failed to turn up.",
        "",
        "## The protein axis",
        "",
        "This is the axis that makes the dataset unusual, and the one to check before trusting",
        "any result. A domain with no near neighbours can be memorised; a cluster of",
        "single-residue variants cannot.",
        "",
        "| cluster size | clusters | domains |",
        "|---:|---:|---:|",
    ]
    for size, n in inv.n_domains.value_counts().sort_index().items():
        lines.append(f"| {size} | {_fmt(n)} | {_fmt(size * n)} |")
    lines += [
        "",
        f"**{_fmt(inv.n_variants.sum())} variant domains sit in {_fmt(len(variants))} clusters.**",
        "A variant is a domain within 5 alignment edits of its cluster's reference — the medoid,",
        "so a wild type is the frame rather than one of its own variants. Positions in",
        "`mut_positions` are in that reference's numbering, so every member of a cluster shares",
        "one coordinate system.",
        "",
        "| family | variant domains | clusters |",
        "|---|---:|---:|",
    ]
    for family, r in by_family[by_family.variants > 0].iterrows():
        lines.append(f"| `{family}` | {r.variants} | {r.clusters} |")

    homeo = int(by_family.loc["Homeodomain", "variants"]) if "Homeodomain" in by_family.index else 0
    lines += [
        "",
        f"Homeodomain carries {homeo} of the {_fmt(inv.n_variants.sum())} variants. The spread",
        "matters more than the total: the project's question — *does sensitivity to",
        "single-residue change transfer across folds?* — is unanswerable from one family, and",
        "answerable only weakly from the families that carry a handful.",
        "",
        "## Evidence quality, per record",
        "",
        "A record is one domain as one source measured it. `reports/label_health.md` carries the",
        "detail; the filter is `label_health.usable(df)`, applied at featurization, not here.",
        "",
        "| verdict | records | meaning |",
        "|---|---:|---|",
    ]
    counts = records.verdict.value_counts()
    meanings = (
        (label_health.OK, "has at least one 8-mer above the cutoff"),
        (label_health.DEAD_VARIANT, "no positives, but its own series has them"),
        (label_health.NO_EVIDENCE, "no positives and no control to read that against"),
    )
    for verdict, meaning in meanings:
        lines.append(f"| `{verdict}` | {_fmt(counts.get(verdict, 0))} | {meaning} |")

    located = int(proteins.dbd_start_protein.notna().sum())
    lines += [
        "",
        "## What else ships with it",
        "",
        f"- **The protein table** (`data/interim/proteins/`): {_fmt(len(proteins))} domains at",
        "  four levels — bare Pfam envelope, padded domain, assayed construct, and full-length",
        f"  protein where one resolves ({_fmt(proteins.full_seq.notna().sum())} domains, of which",
        f"  {_fmt(located)} are located inside it). `uniprot_reviewed` and `uniprot_fragment`",
        "  say whether that full-length sequence is Swiss-Prot and whether it is a fragment.",
        f"- **The cluster inventory** (`data/interim/clusters/`): {_fmt(len(inv))} rows, one per",
        "  cluster, with its seed, its reference, size, variant count and contributing sources.",
        "- **The label-health table** (`data/interim/label_health/`): one row per record, with",
        "  label counts, best E-score and the verdict above.",
        "",
        "## What it does not support",
        "",
        "1. **A held-out score above the noise floor is not a better model.** 47 domains are",
        "   measured by two sources; the median pair agrees on **45.8%** of the 8-mers either",
        "   called positive (`reports/overlap.md`). Two replicates within one source agree on",
        "   70-72%. Anything much past that is reproducing a laboratory.",
        "2. **Cross-fold transfer is thin.** See the family table: most families carry no variant",
        "   at all, so a claim about transfer rests on a handful of clusters.",
        "3. **Near-identical domains can sit in different clusters.** Greedy assignment puts a",
        "   sequence in the first cluster it matches, not the best, so leave-one-cluster-out can",
        "   still leave a close relative in training (`TODO.md` `T27`). Group by connected",
        "   component at evaluation time if that matters.",
        "4. **Full-length protein is the exception.** Roughly a third of domains resolve to one,",
        "   almost entirely because one source publishes no accession. Domain-level and",
        "   construct-level work covers everything.",
        "",
    ]
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    out = DOCS_DIR / "RESULTS.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


def merge_survivors(records: pd.DataFrame) -> pd.DataFrame:
    """The records that reach the merged table: one per domain."""
    from snp2prot import merge

    resolution = merge.resolve(records)
    return resolution[resolution.keep]


if __name__ == "__main__":
    main()
